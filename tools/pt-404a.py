"""Append R-404A (gauge faces only) to js/pt-data.js as PT_REF.extra. Requires: pip install CoolProp
R-404A = R-125/R-143a/R-134a 44/52/4 % by mass (ASHRAE 34). Bubble and dew from the CoolProp HEOS mixture model."""
import CoolProp.CoolProp as CP, json, re
G = lambda pa: round(pa / 6894.757 - 14.696, 1)
AS = CP.AbstractState('HEOS', 'R125&R143a&R134a'); AS.set_mass_fractions([0.44, 0.52, 0.04])
temps = list(range(-40, 151, 5)); out = {'bubble': [], 'dew': []}
for F in temps:
    for Q, k in ((0, 'bubble'), (1, 'dew')):
        v = None
        for d in (0, 0.01, -0.01, 0.05, -0.05):
            try: AS.update(CP.QT_INPUTS, Q, (F + d - 32) / 1.8 + 273.15); v = G(AS.p()); break
            except Exception: pass
        out[k].append(v)
# fill rare misses near the critical point by log-pressure interpolation / drop the tail
for k in out:
    a = out[k]
    for i, v in enumerate(a):
        if v is None and 0 < i < len(a) - 1 and a[i - 1] is not None and a[i + 1] is not None: a[i] = round(((a[i-1] + 14.696) * (a[i+1] + 14.696)) ** .5 - 14.696, 1)
extra = {'R-404A': {**out, 'info': {'kind': {'en': 'Near-azeotrope blend (R-125/R-143a/R-134a)', 'es': 'Mezcla casi azeotrópica (R-125/R-143a/R-134a)'}, 'glide': 0.8, 'note': {'en': 'Low/medium-temp commercial refrigeration; being phased down.', 'es': 'Refrigeración comercial de baja/media temperatura; en reducción.'}}}}
src = open('js/pt-data.js').read(); src = re.sub(r'\n/\* gauge-only extras.*\Z', '', src, flags=re.S)
src += '\n/* gauge-only extras (not in the PT sheet): generated by tools/pt-404a.py with CoolProp. */\nwindow.PT_REF.extra = ' + json.dumps(extra) + ';\n'
open('js/pt-data.js', 'w').write(src); print(out['dew'][16], out['bubble'][16], out['bubble'][-3:])
